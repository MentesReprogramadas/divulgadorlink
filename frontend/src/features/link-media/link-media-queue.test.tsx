import {cleanup,fireEvent,render,screen,waitFor,within} from '@testing-library/react'
import { chooseSelect } from '@/test-select'
import {afterEach,expect,it,vi} from 'vitest'
import {api} from '@/lib/api'
import {LinkMediaQueue} from './link-media-queue'
vi.mock('@/lib/api',()=>({api:vi.fn()}))
vi.mock('@/components/ui/liquid-lens', () => ({ LiquidLens: () => <span aria-hidden="true" /> }))
afterEach(()=>{cleanup();vi.resetAllMocks()})
it('filters attachments by name and kind without mixing text decisions',async()=>{
 vi.mocked(api).mockResolvedValue({status:200,body:{assets:[{id:'icon',linkId:'one',kind:'ICON',name:'Comunidade de livros',version:2,url:'/api/icon'},{id:'cover',linkId:'two',kind:'IMAGE',name:'Clube de estudos',version:4,alt:'Pessoas estudando',url:'/api/cover'}]}})
 render(<LinkMediaQueue/>)
 await screen.findByRole('img',{name:'Pessoas estudando'})
 await chooseSelect(screen.getByLabelText('Tipo de anexo'),'ICON')
 expect(screen.queryByRole('img',{name:'Pessoas estudando'})).toBeNull()
 expect(screen.getByRole('heading',{name:'Comunidade de livros · Ícone'})).toBeTruthy()
 fireEvent.change(screen.getByLabelText('Buscar anexos'),{target:{value:'sem resultado'}})
 expect(await screen.findByText('Nenhum anexo corresponde aos filtros.')).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Limpar filtros de anexos'}))
 expect(await screen.findByRole('img',{name:'Pessoas estudando'})).toBeTruthy()
 expect(vi.mocked(api).mock.calls.filter(([,init])=>init?.method==='POST')).toHaveLength(0)
})
it('clears private previews after access is denied and ignores any asset in the denied payload',async()=>{
 vi.mocked(api).mockResolvedValueOnce({status:200,body:{assets:[{id:'cover',linkId:'one',kind:'IMAGE',name:'Comunidade',version:2,alt:'Foto privada',url:'/api/private'}]}}).mockResolvedValueOnce({status:403,body:{message:'Sem permissão.',assets:[{id:'bad',kind:'IMAGE',alt:'Sentinela proibida',url:'/api/bad'}]}})
 render(<LinkMediaQueue/>)
 await screen.findByRole('img',{name:'Foto privada'})
 fireEvent.click(screen.getByRole('button',{name:'Atualizar fila de anexos'}))
 await screen.findByRole('alert')
 await waitFor(()=>expect(screen.queryByRole('img')).toBeNull())
 expect(screen.queryByText('Sentinela proibida')).toBeNull()
})
it('approves only the selected asset version and reloads the attachment queue',async()=>{
 vi.mocked(api).mockResolvedValueOnce({status:200,body:{assets:[{id:'cover',linkId:'one',kind:'IMAGE',name:'Comunidade',version:7,alt:'Comunidade reunida',url:'/api/private'}]}}).mockResolvedValueOnce({status:200,body:{}}).mockResolvedValueOnce({status:200,body:{assets:[]}})
 render(<LinkMediaQueue/>)
 fireEvent.click(await screen.findByRole('button',{name:'Aprovar anexo'}))
 await screen.findByText('Nenhum anexo aguardando análise.')
 expect(api).toHaveBeenCalledWith('/v1/admin/moderation/media/cover',{method:'POST',body:JSON.stringify({expectedVersion:7,decision:'APPROVE'})})
 expect(vi.mocked(api).mock.calls.filter(([path])=>path==='/v1/admin/moderation/media')).toHaveLength(2)
})
it('filters on the server and allows rejecting an ineligible old pending item',async()=>{
 vi.mocked(api).mockResolvedValue({status:200,body:{assets:[{id:'pending',linkId:'late-link',kind:'IMAGE',alt:'Foto',name:'Retirado',version:3,url:'/api/v1/admin/moderation/media/pending/bytes',canApprove:false}]}})
 render(<LinkMediaQueue linkId="late-link"/>)
 expect((await screen.findByRole('button',{name:'Aprovar anexo'}) as HTMLButtonElement).disabled).toBe(true)
 expect((screen.getByRole('button',{name:'Rejeitar anexo'}) as HTMLButtonElement).disabled).toBe(false)
 expect(api).toHaveBeenCalledWith('/v1/admin/moderation/media?linkId=late-link')
})
it('requires rejection reason and preserves the pending preview on stale review',async()=>{
 vi.mocked(api).mockImplementation(async(_path,init)=>init?.method==='POST'?{status:409,body:{message:'Este anexo mudou.'}}:{status:200,body:{assets:[{id:'pending',linkId:'link',kind:'IMAGE',alt:'Comunidade reunida',name:'Comunidade',version:3,url:'/api/v1/admin/moderation/media/pending/bytes'}]}})
 render(<LinkMediaQueue/>)
 const reject=await screen.findByRole('button',{name:'Rejeitar anexo'})
 expect(screen.queryByLabelText('Motivo da recusa')).toBeNull()
 fireEvent.click(reject)
 const dialog=within(await screen.findByRole('dialog',{name:'Rejeitar anexo'}))
 expect(dialog.getByLabelText('Motivo da recusa').hasAttribute('required')).toBe(true)
 expect(vi.mocked(api).mock.calls.filter(([,init])=>init?.method==='POST')).toHaveLength(0)
 fireEvent.change(dialog.getByLabelText('Motivo da recusa'),{target:{value:'Imagem inadequada'}})
 fireEvent.click(dialog.getByRole('button',{name:'Confirmar rejeição'}));expect((await dialog.findByRole('alert')).textContent).toContain('mudou')
 expect(document.querySelector('img[alt="Comunidade reunida"]')).toBeTruthy()
 expect(JSON.parse(vi.mocked(api).mock.calls.at(-1)![1]!.body as string)).toEqual({expectedVersion:3,decision:'REJECT',reason:'Imagem inadequada'})
})
