import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('calendário personalizado: teclado, envio, fechamento, foco e layout', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-17T12:00:00-03:00'))
  await page.goto('/iframe.html?id=design-system-campos-datepicker--default&viewMode=story')
  const input = page.getByLabel('Data', { exact: true })
  await expect(input).toHaveValue('17/10/2026')
  const trigger = page.getByRole('button', { name: 'Abrir calendário' })
  await trigger.focus(); await page.keyboard.press('Enter')
  const selected = page.getByRole('button', { name: '17 de outubro de 2026', exact: true })
  await expect(selected).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button', { name: '18 de outubro de 2026', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(input).toHaveValue('18/10/2026')
  await expect(trigger).toBeFocused()
  await expect(page.locator('input[type=hidden][name=date]')).toHaveValue('2026-10-18')
  await trigger.click(); await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  const popup = page.getByRole('dialog')
  await expect(popup).toBeVisible()
  expect((await new AxeBuilder({ page }).include('[role="dialog"]').analyze()).violations).toEqual([])
  const box = await popup.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: test.info().outputPath('calendar.png'), animations: 'disabled' })
  await page.getByRole('button', { name: 'Limpar', exact: true }).click()
  await expect(input).toHaveValue('')
  await input.fill('31/02/2026')
  expect(await input.evaluate((element: HTMLInputElement) => element.checkValidity())).toBe(false)
  await input.fill('28/02/2026')
  expect(await input.evaluate((element: HTMLInputElement) => element.checkValidity())).toBe(true)
  await trigger.click(); await page.getByRole('button', { name: 'Hoje', exact: true }).click()
  await expect(input).toHaveValue('17/10/2026')
  await page.setViewportSize({ width: 320, height: 700 })
  await trigger.click()
  const small = await popup.boundingBox()
  expect(small!.x + small!.width).toBeLessThanOrEqual(320)
})

test('data e hora mantêm horário local e disabled impede abrir', async ({ page }) => {
  await page.goto('/iframe.html?id=design-system-campos-datepicker--date-and-time&viewMode=story')
  const input = page.getByLabel('Data', { exact: true })
  await expect(input).toHaveValue('17/10/2026 14:30')
  await page.getByRole('button', { name: 'Abrir calendário' }).click()
  await page.getByRole('button', { name: '20 de outubro de 2026', exact: true }).click()
  await expect(input).toHaveValue('20/10/2026 14:30')
  await input.fill('20/10/2026 24:00')
  expect(await input.evaluate((element: HTMLInputElement) => element.checkValidity())).toBe(false)
  await page.goto('/iframe.html?id=design-system-campos-datepicker--disabled&viewMode=story')
  await expect(page.getByLabel('Data', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Abrir calendário' })).toBeDisabled()
})

test('calendário dentro do modal preserva seleção e fecha somente o calendário', async ({ page }) => {
  await page.goto('/iframe.html?id=design-system-campos-datepicker--in-dialog&viewMode=story')
  const parent = page.getByRole('dialog', { name: 'Prazo do destaque' })
  await expect(parent).toBeVisible()
  const trigger = parent.getByRole('button', { name: 'Abrir calendário' })
  await trigger.click()
  await page.getByRole('button', { name: '20 de outubro de 2026', exact: true }).click()
  await expect(parent.getByLabel('Término')).toHaveValue('20/10/2026 14:30')
  await trigger.click(); await page.keyboard.press('Escape')
  await expect(parent).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(trigger).toBeFocused()
})
