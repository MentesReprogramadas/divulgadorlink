async function stableModalSelect(page: Page, label: string, info: TestInfo, shot: string) {
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('combobox', { name: label, exact: true }) })
  const control = dialog.getByRole('combobox', { name: label, exact: true })
  const geometry = () => dialog.evaluate(element => {
    const rect = element.getBoundingClientRect()
    return { width: rect.width, height: rect.height, scrollWidth: element.scrollWidth, clientWidth: element.clientWidth, scrollHeight: element.scrollHeight, clientHeight: element.clientHeight }
  })
  const before = await geometry()
  await control.click(); await expect(page.getByRole('listbox')).toBeVisible()
  await page.screenshot({ path: info.outputPath(shot + '.png'), animations: 'disabled' })
  const after = await geometry()
  expect(after.width, JSON.stringify({ before, after })).toBeCloseTo(before.width, 0)
  expect(after.height, JSON.stringify({ before, after })).toBeCloseTo(before.height, 0)
  expect(after.scrollWidth).toBeLessThanOrEqual(after.clientWidth + 1)
  expect(after.scrollHeight - after.clientHeight).toBeLessThanOrEqual(Math.max(0, before.scrollHeight - before.clientHeight) + 1)
  const popup = await page.getByRole('listbox').boundingBox()
  expect(popup).not.toBeNull()
  expect(popup!.x).toBeGreaterThanOrEqual(0)
  expect(popup!.x + popup!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.keyboard.press('Escape'); await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(dialog).toBeVisible(); await expect(control).toBeFocused()
}

