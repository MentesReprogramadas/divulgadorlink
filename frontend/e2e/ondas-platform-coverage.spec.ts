for (const theme of ['Areia', 'Botânico']) test('Ondas publicação real ' + theme + ', contato e preservação da paleta', async ({ page, browser }, info) => {
  const fixture = isolatedFixture()
  await login(page, fixture)
  await saveProfile(page, fixture, theme)
  await publishProfile(page)
  const configured = await roadmapApi(page, '/me/forms', 'PUT', {
    expectedVersion: 0,
    definition: { enabled: true, purpose: 'contact', marketingAllowed: true, fields: [{ key: 'name', required: false }, { key: 'email', required: true }, { key: 'message', required: false }] },
  })
  expect(configured.status, JSON.stringify(configured.body)).toBe(200)
  const context = await browser.newContext({ viewport: page.viewportSize()!, locale: 'pt-BR', reducedMotion: 'reduce', isMobile: Boolean(info.project.use.isMobile), hasTouch: Boolean(info.project.use.hasTouch) })
  try {
    await context.addCookies([{ name: 'tla_consent', value: 'denied', domain: fixture.host, path: '/' }])
    const visitor = await context.newPage()
    await visitor.emulateMedia({ reducedMotion: 'reduce' })
    await visit(visitor, fixture, '/p/' + fixture.profileSlug)
    await expect(visitor.getByRole('heading', { name: 'Ana Ondas', exact: true })).toBeVisible()
    await expect(visitor.locator('[data-ink]')).toHaveAttribute('data-ink', theme === 'Botânico' ? 'light' : 'dark')
    const form = visitor.getByRole('region', { name: 'Formulário de contato' })
    await expect(form.getByRole('heading', { name: 'Fale comigo' })).toBeVisible()
    await expect(form.getByRole('checkbox')).not.toBeChecked()
    await audit(visitor, info, 'public-profile-' + theme)
    await form.getByLabel('E-mail', { exact: true }).fill('visitor@fixture.test')
    await form.getByLabel('Mensagem', { exact: true }).fill('Contato de validação Ondas')
    await form.getByRole('button', { name: 'Enviar contato' }).focus()
    await visitor.keyboard.press('Enter')
    await expect(visitor.getByText('Sua mensagem foi recebida.', { exact: true })).toBeVisible()
    expect((await roadmapApi(visitor, '/me/forms/submissions')).status).toBe(401)
    expect((await roadmapApi(page, '/me/forms/submissions')).body.items).toHaveLength(1)
    await audit(visitor, info, 'public-contact-success-' + theme)
  } finally { await context.close() }
})

test('Ondas campanhas, canais e mídia kit com recursos publicados', async ({ page, browser }, info) => {
  test.setTimeout(240_000)
  const fixture = isolatedFixture()
  await login(page, fixture)
  await saveProfile(page, fixture)
  const source = await redirect(page, 'Canal da comunidade')
  const groupId = randomUUID(), channelId = randomUUID()
  const group = await roadmapApi(page, '/me/profile/channel-groups/' + groupId, 'PUT', {
    name: 'Participe da comunidade', visible: true, expectedVersion: 1,
    channels: [{ id: channelId, label: 'Abrir comunidade', networkId: null, destinationRevisionId: source.destinationRevision.id, paused: false }],
  })
  expect(group.status, JSON.stringify(group.body)).toBe(200)
  await visit(page, fixture, '/painel/perfil/canais/' + groupId)
  await expect(page.getByLabel('Título do grupo de canais')).toHaveValue('Participe da comunidade')
  await audit(page, info, 'channel-group-editor')
  await publishProfile(page)
  grantProfileCapability(fixture, 'profile.analytics')
  const sources = await roadmapApi(page, '/me/profile/campaign-sources')
  expect(sources.status).toBe(200)
  const revisionId = sources.body.revisions[0].id as string
  const revision = await roadmapApi(page, '/me/profile/campaign-sources/' + revisionId)
  const campaign = await roadmapApi(page, '/me/profile/campaigns', 'POST', {
    name: 'Campanha Ondas', slug: fixture.campaignSlug, sourceRevisionId: revisionId,
    itemSelection: [revision.body.content.items.find((item: { type: string }) => item.type === 'URL').id],
  })
  expect(campaign.status, JSON.stringify(campaign.body)).toBe(200)
  const campaignId = campaign.body.id as string
  await visit(page, fixture, '/painel/perfil/campanhas/' + campaignId + '/previa')
  await expect(page.getByRole('region', { name: 'Modo de prévia', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Ana Ondas', exact: true })).toBeVisible()
  await audit(page, info, 'campaign-preview')
  expect((await roadmapApi(page, '/me/profile/campaigns/' + campaignId + '/publish', 'POST', { expectedVersion: campaign.body.version })).status).toBe(200)
  await visit(page, fixture, '/painel/perfil/campanhas/' + campaignId + '/metricas')
  await expect(page.getByRole('region', { name: 'Métricas da campanha', exact: true })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByText('Visitas medidas', { exact: true })).toBeVisible()
  await audit(page, info, 'campaign-metrics')
  const kit = await roadmapApi(page, '/me/profile/media-kit', 'PATCH', {
    expectedVersion: 0, content: { publicFields: { showBio: true, showPhoto: true, contactIds: [] }, metricSelections: [], manualMetrics: [{ platform: 'INSTAGRAM', value: 12500, asOf: '2026-10-18' }] },
  })
  expect(kit.status, JSON.stringify(kit.body)).toBe(200)
  expect((await roadmapApi(page, '/me/profile/media-kit/publish', 'POST', { expectedVersion: kit.body.version })).status).toBe(200)
  await visit(page, fixture, '/painel/perfil/midia-kit/previa')
  await expect(page.getByRole('heading', { name: 'Ana Ondas', exact: true })).toBeVisible()
  await audit(page, info, 'media-kit-preview')
  const context = await browser.newContext({ viewport: page.viewportSize()!, locale: 'pt-BR', reducedMotion: 'reduce', isMobile: Boolean(info.project.use.isMobile), hasTouch: Boolean(info.project.use.hasTouch) })
  try {
    await context.addCookies([{ name: 'tla_consent', value: 'denied', domain: fixture.host, path: '/' }])
    const visitor = await context.newPage()
    for (const [route, label] of [['/p/' + fixture.profileSlug + '/c/' + fixture.campaignSlug, 'campaign-public'], ['/p/' + fixture.profileSlug + '/midia-kit', 'media-kit-public']] as const) {
      await visit(visitor, fixture, route)
      await expect(visitor.getByRole('heading', { name: 'Ana Ondas', exact: true })).toBeVisible()
      if (label === 'media-kit-public') await expect(visitor.getByText(/Informado pelo proprietário/)).toBeVisible()
      await audit(visitor, info, label)
    }
    await visit(visitor, fixture, '/p/' + fixture.profileSlug)
    const channel = visitor.getByRole('link', { name: 'Site: Abrir comunidade', exact: true })
    await expect(channel).toBeVisible()
    const choice = await channel.getAttribute('href')
    expect(choice).toContain('/p/' + fixture.profileSlug + '/canais/')
    const disabled = await roadmapApi(page, '/me/redirects/' + source.id + '/disable', 'POST', { expectedRevision: source.version })
    expect(disabled.status).toBe(200)
    const response = await visitor.goto(new URL(choice!, fixture.origin).toString())
    expect(response?.status()).toBe(200)
    expect(new URL(visitor.url()).pathname).toBe('/p/' + fixture.profileSlug + '/canais/estado')
    await expect(visitor.getByRole('heading', { name: 'Canal indisponível', exact: true })).toBeVisible()
    await audit(visitor, info, 'channel-unavailable')
  } finally { await context.close() }
})

