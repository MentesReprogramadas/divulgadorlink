test('Ondas coleção publicada, distribuição e comprovação pública de domínio', async ({ page, browser, request }, info) => {
  test.setTimeout(240_000)
  const fixture = isolatedFixture()
  await login(page, fixture)
  const linkId = randomUUID(), collectionId = randomUUID()
  sql(`INSERT INTO links(id,"tenantId","ownerId","canonicalUrl",name,description,"networkId","nicheId",status,"occupiesSlot","everPublished","updatedAt") VALUES('${linkId}','${fixture.tenantId}','${fixture.otherId}','https://example.com/ondas','Comunidade Ondas','Encontros e materiais de estudo',(SELECT id FROM networks WHERE "tenantId"='${fixture.tenantId}' AND slug='site'),(SELECT id FROM niches WHERE "tenantId"='${fixture.tenantId}' AND "requiresAge"=false LIMIT 1),'PUBLISHED',false,true,now())`)
  const favorite = await roadmapApi(page, '/me/favorites/' + linkId, 'PUT')
  expect(favorite.status).toBe(200)
  expect((await roadmapApi(page, '/me/collections', 'POST', { id: collectionId, name: 'Estudos Ondas' })).status).toBe(200)
  expect((await roadmapApi(page, '/me/collections/' + collectionId + '/items/' + favorite.body.favoriteId, 'PUT', { expectedVersion: 0 })).status).toBe(200)
  await visit(page, fixture, '/painel/favoritos')
  await page.getByRole('tab', { name: 'Coleções', exact: true }).click()
  await page.getByRole('region', { name: 'Suas coleções' }).getByRole('button', { name: 'Estudos Ondas Abrir coleção', exact: true }).click()
  await page.getByRole('button', { name: 'Publicar coleção', exact: true }).click()
  await page.getByLabel('Nome do curador').fill('Ana Curadora')
  await page.getByLabel('Endereço da coleção').fill(fixture.collectionSlug)
  const publication = page.waitForResponse(response => response.url().includes('/me/collections/' + collectionId + '/publish') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Publicar seleção', exact: true }).click()
  const published = await publication
  expect(published.status(), await published.text()).toBe(200)
  await expect(page.getByRole('link', { name: 'Ver coleção pública' })).toBeVisible()
  const base = await redirect(page, 'Entrada da comunidade'), target = await redirect(page, 'Grupo de estudos', 'https://example.com/f12-b')
  await visit(page, fixture, '/painel/convites/' + base.id + '/distribuicao')
  await expect(page.getByRole('region', { name: 'Distribuir acessos', exact: true })).not.toHaveAttribute('aria-busy', 'true')
  await expect(page.getByText('/r/' + base.id, { exact: true })).toBeVisible()
  await audit(page, info, 'distribution-empty')
  const pool = await roadmapApi(page, '/me/redirects/' + base.id + '/pool', 'PUT', { expectedVersion: 0, destinations: [{ revisionId: target.destinationRevision.id, weight: 1, paused: false }] })
  expect(pool.status, JSON.stringify(pool.body)).toBe(200)
  await page.reload()
  await expect(page.getByText('Distribuição ativa', { exact: true })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Grupo de estudos', exact: true })).toBeVisible()
  await audit(page, info, 'distribution-active')
  const challenge = await roadmapApi(page, '/me/redirects/' + base.id + '/ownership/challenges', 'POST', { revisionId: base.destinationRevision.id })
  expect(challenge.status).toBe(200)
  expect((await request.put(runtime.stubOrigin + '/ownership-file', { data: challenge.body.content })).status()).toBe(200)
  const verified = await roadmapApi(page, '/me/redirects/' + base.id + '/ownership/verify', 'POST', { challengeId: challenge.body.id })
  expect(verified.status, JSON.stringify(verified.body)).toBe(200)
  const context = await browser.newContext({ viewport: page.viewportSize()!, locale: 'pt-BR', reducedMotion: 'reduce', isMobile: Boolean(info.project.use.isMobile), hasTouch: Boolean(info.project.use.hasTouch) })
  try {
    await context.addCookies([{ name: 'tla_consent', value: 'denied', domain: fixture.host, path: '/' }])
    const visitor = await context.newPage()
    await visit(visitor, fixture, '/colecoes/' + fixture.collectionSlug)
    await expect(visitor.getByRole('heading', { name: 'Estudos Ondas', exact: true })).toBeVisible()
    await expect(visitor.getByText('Curadoria de Ana Curadora')).toBeVisible()
    await expect(visitor.getByRole('link', { name: 'Comunidade Ondas', exact: true })).toBeVisible()
    await audit(visitor, info, 'collection-public')
    await visit(visitor, fixture, '/verificacao/' + base.id)
    await expect(visitor.getByText('Controle do domínio comprovado', { exact: true })).toBeVisible()
    expect(await visitor.content()).not.toContain(challenge.body.content)
    await audit(visitor, info, 'ownership-verified')
    expect((await roadmapApi(page, '/me/redirects/' + base.id + '/ownership', 'DELETE')).status).toBe(200)
    await visitor.reload()
    await expect(visitor.getByText('Nenhuma comprovação válida para este destino.')).toBeVisible()
    await audit(visitor, info, 'ownership-revoked')
    expect((await roadmapApi(page, '/me/redirects/' + base.id + '/pool/' + target.destinationRevision.id, 'PATCH', { paused: true, expectedVersion: pool.body.version })).status).toBe(200)
    const response = await visitor.goto(fixture.origin + '/r/' + base.id)
    expect(response?.status()).toBe(200)
    expect(new URL(visitor.url()).pathname).toBe('/r/' + base.id + '/estado')
    await expect(visitor.getByRole('heading', { name: 'Link permanente indisponível', exact: true })).toBeVisible()
    await audit(visitor, info, 'redirect-unavailable')
  } finally { await context.close() }
})
